def predict_essay(text, model, tokenizer, device, max_length=512, with_prompt=False):
    """Predict score for an essay"""
    if with_prompt:
        text = f"Rate this IELTS essay quality on a scale from 0 to 19: {text}"

    encoding = tokenizer(
        text,
        max_length=max_length,
        padding='max_length',
        truncation=True,
        return_tensors='pt'
    )

    input_ids = encoding['input_ids'].to(device)
    attention_mask = encoding['attention_mask'].to(device)

    with torch.no_grad():
        outputs = model(input_ids, attention_mask)
        logits = outputs.logits
        pred = torch.argmax(logits, dim=1).item()
        probs = torch.softmax(logits, dim=1).cpu().numpy()[0]

        # Get top 3 predictions
        top3_indices = probs.argsort()[-3:][::-1]
        top3 = [(idx, probs[idx]) for idx in top3_indices]

    return pred, top3, probs

