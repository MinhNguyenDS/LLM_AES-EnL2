def clean_band_score(band_str):
    """Convert IELTS band to 0-19"""
    try:
        band_str = str(band_str).strip().replace('\n', '').replace('\r', '')
        if '<' in band_str:
            return 3
        match = re.search(r'(\d+\.?\d*)', band_str)
        if match:
            band_score = float(match.group(1))
            return max(0, min(19, int(round((band_score / 9.0) * 19))))
        return 10
    except:
        return 10

def preprocess_data(csv_file):
    df = pd.read_csv(csv_file)
    print(f"  {csv_file}: {len(df)} rows")

    texts = df['essay'].astype(str) if 'essay' in df.columns else df.iloc[:, 0].astype(str)
    scores = df['band'].apply(clean_band_score) if 'band' in df.columns else df.iloc[:, 1].apply(clean_band_score)

    new_df = pd.DataFrame({'text': texts, 'score': scores})
    new_df = new_df[new_df['text'].str.strip() != '']
    new_df = new_df[new_df['text'] != 'nan'].drop_duplicates(subset=['text'])

    print(f"  After cleaning: {len(new_df)} rows, scores {new_df['score'].min()}-{new_df['score'].max()}")
    return new_df

